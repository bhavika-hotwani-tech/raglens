"""
Authentication & JWT Service.

WHAT: Provides cryptographic password hashing, verification, and JWT creation/decoding.
WHY: Ensures enterprise passwords are never stored in plaintext and issues stateless,
     tamper-proof JWT tokens for client authorization.
"""

from datetime import datetime, timedelta, timezone
from typing import Optional, Dict, Any
from passlib.context import CryptContext
from jose import JWTError, jwt
from app.config import settings

# Configure CryptContext for password hashing using bcrypt
# Passlib handles salting and adaptive work factor automatically
pwd_context = CryptContext(schemes=["bcrypt"], deprecated="auto")


def hash_password(password: str) -> str:
    """
    Hashes a plaintext password with a random salt using bcrypt.
    WHY: Protects user credentials in case of database compromise.
    """
    return pwd_context.hash(password)


def verify_password(plain_password: str, hashed_password: str) -> bool:
    """
    Verifies a plaintext password against an existing bcrypt hash.
    WHY: Constant-time comparison prevents timing attack vulnerabilities.
    """
    return pwd_context.verify(plain_password, hashed_password)


def create_access_token(data: Dict[str, Any], expires_delta: Optional[timedelta] = None) -> str:
    """
    Encodes claims into a signed JWT string.
    WHAT: Sets expiration timestamp ('exp') and signs with HMAC-SHA256 secret.
    WHY: Allows the frontend to make authenticated requests without database lookups on every route.
    """
    to_encode = data.copy()
    if expires_delta:
        expire = datetime.now(timezone.utc) + expires_delta
    else:
        expire = datetime.now(timezone.utc) + timedelta(minutes=settings.ACCESS_TOKEN_EXPIRE_MINUTES)

    to_encode.update({"exp": expire})
    encoded_jwt = jwt.encode(to_encode, settings.JWT_SECRET_KEY, algorithm=settings.JWT_ALGORITHM)
    return encoded_jwt


def decode_access_token(token: str) -> Optional[Dict[str, Any]]:
    """
    Decodes and validates signature of a JWT token.
    WHAT: Verifies cryptographic integrity and expiration date.
    WHY: Guarantees the token was generated by this server and has not been altered or expired.
    """
    try:
        payload = jwt.decode(token, settings.JWT_SECRET_KEY, algorithms=[settings.JWT_ALGORITHM])
        return payload
    except JWTError:
        return None
